        //Using pointF[] which is a structure to represent 2d coordinates which can then be used to draw the arrow shape
        private PointF[] GetPlayerArrowPoints(int x, int y, Direction facing, int tileSize)
        {
            return facing switch //Using a switch statement to draw the arrow based on the players rotation/facing direction
            {
                Direction.Up => new PointF[] { new(x * tileSize + 10, y * tileSize), new(x * tileSize, y * tileSize + 20), new(x * tileSize + 20, y * tileSize + 20) },
                Direction.Down => new PointF[] { new(x * tileSize + 10, y * tileSize + 20), new(x * tileSize, y * tileSize), new(x * tileSize + 20, y * tileSize) },
                Direction.Left => new PointF[] { new(x * tileSize, y * tileSize + 10), new(x * tileSize + 20, y * tileSize), new(x * tileSize + 20, y * tileSize + 20) },
                Direction.Right => new PointF[] { new(x * tileSize + 20, y * tileSize + 10), new(x * tileSize, y * tileSize), new(x * tileSize, y * tileSize + 20) },
                _ => new PointF[] { new(x * tileSize + 10, y * tileSize), new(x * tileSize, y * tileSize + 20), new(x * tileSize + 20, y * tileSize + 20) }
            };
        }
        private async void ExecuteCommands(object sender, EventArgs e, bool isAutoComplete) //Method to exectute commands / detect wins / request new games
        {
            string[] commands = isAutoComplete //If autocomplete is true, meaning autocomplete was used
                ? autoCompleteOutput.Text.Trim().Split(',') //Then take commands from the autocomplete output
                : inputBox.Text.Trim().Split(','); //Otherwise take the commands from the input box

            bool hitWall = false; //set hitwall to false

            foreach (string command in commands) //For each command in the string array
            {
                string trimmedCmd = command.Trim(); //Making a new variable for the trimmed command (no spaces so it can be validated properly)
                if (!System.Text.RegularExpressions.Regex.IsMatch(trimmedCmd, @"^(Move\[\d+\]|Turn\[[RL]\])$", System.Text.RegularExpressions.RegexOptions.IgnoreCase))
                //^^^If the command starts witch Move[ then a positive digit, then ] OR starts with Turn[ R or L and then ] it is valid
                {
                    MessageBox.Show("Invalid input! Use only Move[n] or Turn[R/L]", "Input Error"); //Display a message box for a validation error
                    return; //stop execution of the command
                }

                if (trimmedCmd.StartsWith("Move[") && trimmedCmd.EndsWith("]")) //If the current command is a move command
                {
                    int steps = int.Parse(trimmedCmd.Substring(5, trimmedCmd.Length - 6)); //Convert the command into just the amount of steps taken (Move[steps])
                    //^This has to be done like this incase steps is multiple digits
                    for (int i = 0; i < steps; i++)
                    {
                        if (!player.Move(player.Facing)) //Call to move the player in the current facing direction, if failed then a wall must be hit
                        {
                            hitWall = true; //So set wall to hit
                            break; //And stop movement
                        }
                        Invalidate(); //Redraw the maze
                        await Task.Delay(200); //Delay between movement
                    }
                }
                else if (trimmedCmd.StartsWith("Turn[") && trimmedCmd.EndsWith("]")) //If the current command is a move command
                {
                    char turnDirection = trimmedCmd[5]; //Set the turn direction to R or L in the trimmed command
                    player.Turn(turnDirection); //Use the turn method from the player class to turn the player in the turn direction
                    Invalidate();
                    await Task.Delay(200);
                }

                if (hitWall) break; //Stop movement if a wall was hit
            }

            //Checking for wins/losses/autocomplete win
            if (hitWall) //If the player hit a wall
            {
                MessageBox.Show("You lost: You hit a wall!", "Game Over"); //Display message 
            }
            else if (player.X == endPoint.x && player.Y == endPoint.y && isAutoComplete == false) //If the [player is in the winning position and not autocompleted
            {
                MessageBox.Show("You won: You reached the end!", "Victory"); //Display message and increment wins
                GamesWon++; 
            }
            else if (player.X == endPoint.x && player.Y == endPoint.y && isAutoComplete == true) //If the [player is in the winning position and autocompleted
            {
                MessageBox.Show("This does not count as a win.", "Maze Autocompleted"); //Display message
                //Not incrementing player wins
            }
            else if (!(player.X == endPoint.x && player.Y == endPoint.y) && isAutoComplete == true) //If the player is NOT in the winning position, but autocomplete is on and finished moving
            {
                //This means that autocomplete failed so display message for debugging
                MessageBox.Show("Could not complete maze.", "Autocomplete Failed");
                //Not incrementing player wins
            }
            else //Otherwise, the player has entered not enough moves to reach the end
            {
                MessageBox.Show("You lost: You didn't reach the end!", "Game Over"); //Display message
            }
            currentLevel++; //Increment the current level and call new game method
            NewGame();
        }
        private void NewGame() //Method to start a new game
        {
            if (currentLevel > HomeForm.LevelCount) //If the current level matches the level count
            {
                MessageBox.Show($"You passed {GamesWon}/{HomeForm.LevelCount} levels.", "Returning to home"); //Show how many levels passed out of chosen amount and return to home
                Close(); //Close gameform
                Application.Restart(); //Restart application
                return; //End further execution of code
            }

            //Otherwise generate a new maze using mazegenerator class
            mazeGenerator = new MazeGenerator(19, 19);
            maze = mazeGenerator.GetMaze();
            endPoint = mazeGenerator.GetEndPoint();
            player = new Player(maze); //making player again using player class

            Invalidate(); //redraw new random maze
        }
