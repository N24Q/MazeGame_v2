        private void AutoCompleteMaze(object sender, EventArgs e) //Method to autocomplete the maze using Pathfinder class
        {
            Pathfinder pathfinder = new Pathfinder(maze, (player.X, player.Y), endPoint); //Pathfinder class containing the maze, player coords and end point
            List<(int, int)> path = pathfinder.FindPath(); //Creating a path of coordinatings using the FindPath() method in pathfinder class

            if (path.Count == 0) //If there are no coordinates in the path list, this means the pathfinder failed - handle this with an error message
            {
                MessageBox.Show("No valid path found!", "Error");
                return;
            }

            List<string> commands = pathfinder.TranslateToCommands(path); //Using the translatetocommands method in pathfinder class to turn the path list into a list of executable commands
            autoCompleteOutput.Text = string.Join(", ", commands); //Adding the commands list to the autoCompleteOutput textbox (THIS IS FOR DEBUGGING PATHFINDER)
            ExecuteCommands(sender, e, true); //Then pass TRUE for bool isAutoComplete, obj and eventargs are not used in this case
        }
        protected override void OnPaint(PaintEventArgs e) //Method to draw the maze and character using graphics
        {
            base.OnPaint(e); //
            int tileSize = 20; //Setting the tile size

            for (int x = 0; x < maze.GetLength(0); x++) //Looping through the maze grid generated by the maze (this.maze) from the MazeGenerator class
            {
                for (int y = 0; y < maze.GetLength(1); y++)
                {
                    Brush brush = maze[x, y] switch //Using a switch case to choose colour based on the number used to represent different colours 
                    {
                        0 => Brushes.Black, //Black = border
                        1 => (x + y) % 2 == 0 ? Brushes.White : Brushes.LightGray, //Using ternary operators to draw a grid pattern out of white and light grey, just for visibility of tiles
                        2 => Brushes.Green, //Green = Startpoint
                        3 => Brushes.Red, //Red = Endpoint
                        _ => Brushes.Gray //Using grey as a fallback incase of a number in maze not matching any switch case (good for error detecting because it shows up)
                    };
                    e.Graphics.FillRectangle(brush, x * tileSize, y * tileSize, tileSize, tileSize);
                }
            }
            //Creating an arrow to represent the player in blue using GetPlayerArrowPoints()
            PointF[] arrow = GetPlayerArrowPoints(player.X, player.Y, player.Facing, tileSize);
            e.Graphics.FillPolygon(Brushes.Blue, arrow); //Drawing the arrow using FillPolygon function of graphics
        }
